    template_id        NUMBER CONSTRAINT fk_ws_services_template REFERENCES ws_service_templates(id) ON DELETE SET NULL,
    name               VARCHAR2(150) NOT NULL,
    service_date       DATE NOT NULL,
    start_time         VARCHAR2(10) DEFAULT '10:00',
    status             VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL CONSTRAINT ck_ws_services_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'COMPLETED', 'CANCELLED')),
    band_id            NUMBER CONSTRAINT fk_ws_services_band REFERENCES ws_bands(id) ON DELETE SET NULL,
    notes              VARCHAR2(1000),
    row_version_number NUMBER DEFAULT 1 NOT NULL,
    created_at         TIMESTAMP WITH LOCAL TIME ZONE DEFAULT LOCALTIMESTAMP NOT NULL,
