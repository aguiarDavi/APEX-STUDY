-- Drop objects if existing (clean idempotent replay)
BEGIN
    FOR r IN (SELECT object_name, object_type 
                FROM user_objects 
               WHERE object_name LIKE 'WS_%' 
                 AND object_type IN ('VIEW', 'TABLE')) LOOP
        BEGIN
            IF r.object_type = 'VIEW' THEN
                EXECUTE IMMEDIATE 'DROP VIEW ' || r.object_name;
            ELSIF r.object_type = 'TABLE' THEN
                EXECUTE IMMEDIATE 'DROP TABLE ' || r.object_name || ' CASCADE CONSTRAINTS PURGE';
            END IF;
        EXCEPTION
            WHEN OTHERS THEN NULL;
        END;
    END LOOP;
END;
