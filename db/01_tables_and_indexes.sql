-- ----------------------------------------------------------------------------
-- 1. WS_MEMBERS
-- ----------------------------------------------------------------------------
CREATE TABLE ws_members (
    id                 NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_ws_members PRIMARY KEY,
    username           VARCHAR2(100) NOT NULL CONSTRAINT uq_ws_members_username UNIQUE,
    full_name          VARCHAR2(150) NOT NULL,
    email              VARCHAR2(255) NOT NULL CONSTRAINT uq_ws_members_email UNIQUE,
    phone              VARCHAR2(50),
    member_role        VARCHAR2(30) DEFAULT 'MUSICIAN' NOT NULL CONSTRAINT ck_ws_members_role CHECK (member_role IN ('LEADER', 'MUSICIAN', 'ADMIN', 'TECH')),
    max_services_month NUMBER DEFAULT 4 NOT NULL,
    is_active          VARCHAR2(1) DEFAULT 'Y' NOT NULL CONSTRAINT ck_ws_members_active CHECK (is_active IN ('Y', 'N')),
    created_at         TIMESTAMP WITH LOCAL TIME ZONE DEFAULT LOCALTIMESTAMP NOT NULL,
    created_by         VARCHAR2(100),
    updated_at         TIMESTAMP WITH LOCAL TIME ZONE,
    updated_by         VARCHAR2(100)
);

-- ----------------------------------------------------------------------------
-- 2. WS_INSTRUMENTS
-- ----------------------------------------------------------------------------
CREATE TABLE ws_instruments (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_ws_instruments PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL CONSTRAINT uq_ws_instruments_name UNIQUE,
    code          VARCHAR2(30) NOT NULL CONSTRAINT uq_ws_instruments_code UNIQUE,
    category      VARCHAR2(30) DEFAULT 'BAND' NOT NULL CONSTRAINT ck_ws_instruments_cat CHECK (category IN ('RHYTHM', 'MELODY', 'VOCALS', 'PRODUCTION')),
    display_order NUMBER DEFAULT 0 NOT NULL,
    is_active     VARCHAR2(1) DEFAULT 'Y' NOT NULL CONSTRAINT ck_ws_instruments_active CHECK (is_active IN ('Y', 'N'))
);

-- ----------------------------------------------------------------------------
-- 3. WS_MEMBER_INSTRUMENTS
-- ----------------------------------------------------------------------------
CREATE TABLE ws_member_instruments (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_ws_member_instruments PRIMARY KEY,
