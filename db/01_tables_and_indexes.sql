    skill_level   VARCHAR2(20) DEFAULT 'INTERMEDIATE' NOT NULL CONSTRAINT ck_ws_mi_skill CHECK (skill_level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
    CONSTRAINT uq_ws_member_instruments UNIQUE (member_id, instrument_id)
);

-- ----------------------------------------------------------------------------
-- 4. WS_SERVICE_TEMPLATES
-- ----------------------------------------------------------------------------
CREATE TABLE ws_service_templates (
